/// `"A" | "B"`: the kinds taking `group` (`STYLE`, `INTERACTIVE` or `PARENT`)
fn union(group: u8) -> String {
  let names: Vec<String> = KINDS
    .iter()
    .filter(|(_, caps)| caps & group != 0)
    .map(|(kind, _)| format!("\"{kind}\""))
    .collect();
  names.join(" | ")
}

/// `type StyledKind = ..`, `type InteractiveKind = ..` and `type ParentKind = ..`
pub(crate) fn d_ts() -> String {
  format!(
    "  /** The kinds of element taking style methods. */\n  export type StyledKind = {};\n  /** The kinds of element taking `id`, `on_click`, .. */\n  export type InteractiveKind = {};\n  /** The kinds of element taking `child`. */\n  export type ParentKind = {};\n",
    union(STYLE),
    union(INTERACTIVE),
    union(PARENT),
  )
}
